#!/bin/bash
# ===========================================================================
#  go.sh 검증 스위트 (test/run_all.sh)
#
#  사용법 : bash test/run_all.sh
#   - nav_test.sh    : 메뉴 이동 스택(b/bb/bbb/0/m) 단위 테스트
#   - env_test.sh    : go.env 메뉴 데이터 정합성 감사 (중복단축키/태그/relay)
#   - menu_test.sh   : 218개 메뉴 본문 파싱 전수 점검
#   - e2e_test.sh    : 실제 go.sh 구동 E2E (Linux+tty 필요, 느림)
#
#  주의 : e2e 는 /dev/tty 를 /dev/stdin 으로 바꿔 구동하므로
#         실제 터미널에서 실행하면 조작이 불가능하므로 CI/자동점검 전용이다.
# ===========================================================================
cd "$(dirname "$0")/.." || exit 1
RC=0
for t in test/nav_test.sh test/env_test.sh test/menu_test.sh; do
    echo "################################################################"
    echo "# $t"
    echo "################################################################"
    bash "$t" || RC=1
    echo
done
if [ "${1:-}" = "--e2e" ]; then
    echo "################################################################"
    echo "# test/e2e_test.sh"
    echo "################################################################"
    bash test/e2e_test.sh || RC=1
fi
[ "$RC" -eq 0 ] && echo "✅ 전체 점검 통과" || echo "❌ 실패 항목 있음"
exit $RC
